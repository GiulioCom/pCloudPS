    https://corp-prod.privilegecloud.cyberark.cloud). Validated strictly against 
    RFC DNS label syntax (alphanumeric characters and hyphens only).

.PARAMETER CsvFilePath
    Specifies the literal path to the source CSV report generated by Get-IdiraAccount.ps1.
    A ValidateScript block verifies that the target path exists and points to a readable leaf file.

.PARAMETER Delete
    Switch parameter acting as a safety gate. When omitted, the script runs in safe audit 
    mode (read-only). When supplied, the script executes destructive removal operations 
    against the identified redundant account IDs.

.PARAMETER log
    Switch parameter. Enables output logging to a timestamped file on disk for compliance 
    and operational tracking.

.PARAMETER logFolder
    Specifies the target directory where execution logs will be written when -log is 
