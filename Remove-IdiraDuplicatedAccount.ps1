    By default, the script executes in read-only simulation mode (Audit / WhatIf), emitting 
    identified duplicate candidates to the pipeline for review without modifying data. 
    When the -Delete switch is explicitly passed, the script initiates account deletion 
    against the target identity or PAM service tenant. Optional file logging captures 
    audit evidence and execution events.

.PARAMETER Username
    Specifies the administrative account or operator identity used to authenticate 
    against the target tenant API endpoints for account deletion.

.PARAMETER subDomain
